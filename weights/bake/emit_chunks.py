#!/usr/bin/env python3
"""Emit chunked inproj wrappers (metaprogramming step for --chunk).

Two wrapper kinds per layer (C = resolved chunk count from chunk.py):

1. P&R leaf  src/generated/layer{N}_inproj_c{K}.v — module
   layer{N}_inproj_c{K} fixes CHUNKS=C, CHUNK=K plus this slice's
   Q/K/V hex bindings, so Yosys elaborates a distinct constant-folded
   netlist per slice (the layer-0-vs-layer-3 differentiation, one level
   down). Each leaf is one LibreLane run (gen_chunk_configs.sh).

2. Sim harness src/generated/layer{N}_inproj_c{C}x.v — instantiates all
   C leaves, concatenates thirds (Q_full={c{C-1}..c{0}} LSB-first, same
   for K/V, frame={V,K,Q}) and exposes the MONOLITHIC port signature,
   so a testbench can prove chunk-concat == monolithic bit-for-bit.

Run chunk.py first (wrappers point at its slice hex files).

Usage:
  python3 weights/bake/emit_chunks.py --chunks 48 [--layers 0-29]
Output: src/generated/*.v (gitignored exhaust).
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from chunk import resolve, parse_layers  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "src", "generated")
CAL = os.path.join(HERE, "scales_cal.json")

LEAF = """// GENERATED by weights/bake/emit_chunks.py — do not hand-edit.
// Layer {n} inproj slice {k}/{c}: this slice's Q/K/V rows baked in.
module layer{n}_inproj_c{k} #(
  parameter S = 64,
  parameter H = 576,
  parameter KV = 192,
  parameter C = 256
)(
  input  wire             clk,
  input  wire             rst_n,
  input  wire [S*H*8-1:0] tok_in,
  input  wire             tok_valid,
  input  wire [15:0]      cfg_scale,
  input  wire [15:0]      cfg_zero,
  output wire             tok_ready,
  output wire [S*{nw}*8-1:0] y_out,
  output wire             y_valid
);
  inproj_tile #(
    .S(S), .H(H), .KV(KV), .C(C),
    .CHUNKS({c}), .CHUNK({k}),
    .QKV_SH(5'd{qkvsh}),
    .WQ_FILE("weights/bake/chunks/c{c}/layer{n}_q_proj_c{k}.hex"),
    .WK_FILE("weights/bake/chunks/c{c}/layer{n}_k_proj_c{k}.hex"),
    .WV_FILE("weights/bake/chunks/c{c}/layer{n}_v_proj_c{k}.hex"),
    .WQ_WIDE_FILE("weights/bake/chunks/c{c}/layer{n}_q_proj_c{k}_w32.hex"),
    .WK_WIDE_FILE("weights/bake/chunks/c{c}/layer{n}_k_proj_c{k}_w32.hex"),
    .WV_WIDE_FILE("weights/bake/chunks/c{c}/layer{n}_v_proj_c{k}_w32.hex")
  ) u_slice (
    .clk(clk), .rst_n(rst_n),
    .tok_in(tok_in), .tok_valid(tok_valid),
    .cfg_scale(cfg_scale), .cfg_zero(cfg_zero),
    .tok_ready(tok_ready), .y_out(y_out), .y_valid(y_valid)
  );
endmodule
"""

HARNESS_HEAD = """// GENERATED by weights/bake/emit_chunks.py — do not hand-edit.
// Layer {n} chunked-inproj harness: {c} slices concatenated to the
// monolithic frame signature (sim equivalence vs inproj_tile default).
module layer{n}_inproj_c{c}x #(
  parameter S = 64,
  parameter H = 576,
  parameter KV = 192,
  parameter C = 256
)(
  input  wire             clk,
  input  wire             rst_n,
  input  wire [S*H*8-1:0] tok_in,
  input  wire             tok_valid,
  input  wire [15:0]      cfg_scale,
  input  wire [15:0]      cfg_zero,
  output wire             tok_ready,
  output wire [S*(H+2*KV)*8-1:0] y_out,
  output wire             y_valid
);
  localparam QN = H / {c};
  localparam KN = KV / {c};
"""

def emit_leaf(n, k, c, qn, kn, qkvsh):
    """Write one P&R leaf wrapper; returns its path."""
    nw = qn + 2 * kn
    path = os.path.join(OUT, "layer%d_inproj_c%d.v" % (n, k))
    with open(path, "w") as f:
        f.write(LEAF.format(n=n, k=k, c=c, nw=nw, qkvsh=qkvsh))
    return path


def emit_harness(n, c):
    """Write one sim-concat harness; returns its path."""
    lines = [HARNESS_HEAD.format(n=n, c=c)]
    for k in range(c):
        lines.append(
            "  wire [S*(QN+2*KN)*8-1:0] ycat_%d;\n" % k
            + "  wire tok_rdy_%d, y_vld_%d;\n" % (k, k)
            + "  layer%d_inproj_c%d #(.S(S), .H(H), .KV(KV), .C(C)) u_c%d (\n"
            % (n, k, k)
            + "    .clk(clk), .rst_n(rst_n), .tok_in(tok_in),\n"
            + "    .tok_valid(tok_valid), .cfg_scale(cfg_scale),\n"
            + "    .cfg_zero(cfg_zero), .tok_ready(tok_rdy_%d),\n" % k
            + "    .y_out(ycat_%d), .y_valid(y_vld_%d));\n" % (k, k))
    # Direct thirds concat (LSB-first = global row order).
    qcat = "{%s}" % ", ".join("ycat_%d[S*QN*8-1:0]" % k
                              for k in range(c - 1, -1, -1))
    kcat = "{%s}" % ", ".join(
        "ycat_%d[S*(QN+KN)*8-1:S*QN*8]" % k for k in range(c - 1, -1, -1))
    vcat = "{%s}" % ", ".join(
        "ycat_%d[S*(QN+2*KN)*8-1:S*(QN+KN)*8]" % k
        for k in range(c - 1, -1, -1))
    lines.append("  assign y_out = {%s, %s, %s};\n" % (vcat, kcat, qcat))
    lines.append("  assign tok_ready = tok_rdy_0;\n")
    lines.append("  assign y_valid = y_vld_0;\nendmodule\n")
    path = os.path.join(OUT, "layer%d_inproj_c%dx.v" % (n, c))
    with open(path, "w") as f:
        f.writelines(lines)
    return path


def main(argv):
    """CLI entry point (see module docstring for usage)."""
    if "--chunks" not in argv:
        print("usage: emit_chunks.py --chunks N [--layers 0-29]")
        return 1
    c = resolve(int(argv[argv.index("--chunks") + 1]))
    layers = list(range(30))
    if "--layers" in argv:
        layers = parse_layers(argv[argv.index("--layers") + 1])
    if c == 1:
        print("monolithic (C=1): emit_layers.py already covers this")
        return 0
    os.makedirs(OUT, exist_ok=True)
    cal = json.load(open(CAL))["layers"]
    qn, kn = 576 // c, 192 // c
    n_leaf = n_har = 0
    for n in layers:
        qkvsh = cal[n]["SC_QKVSH"]
        for k in range(c):
            emit_leaf(n, k, c, qn, kn, qkvsh)
            n_leaf += 1
        emit_harness(n, c)
        n_har += 1
    print("emitted %d leaves + %d harnesses (C=%d) -> %s"
          % (n_leaf, n_har, c, OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
