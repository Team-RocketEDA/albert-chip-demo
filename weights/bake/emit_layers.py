#!/usr/bin/env python3
"""Emit per-layer etched wrappers (metaprogramming step).

One source (layer_etched.v) becomes 30 distinct netlists: each
src/generated/layerN_etched.v fixes LAYER=N, that layer's per-tensor
weight-file bindings (*_pt.hex from bake_pertensor.py), and the
calibrated static-quant scale points (MUL,SH pairs + YQ_SHIFT from
scales_cal.json), so Yosys elaborates 30 unique constant-folded
variants and each layerN_etched LibreLane config has a real top.

Wide SRAM bank images (*_w32.hex, USE_SRAM_W=1 path) are repacked from
the same _pt sources (pack.py --all --pt); the narrow _pt files feed
the byte-bank path. Legacy per-row tables stay for the slice stitch TBs.

Usage: python3 weights/bake/emit_layers.py   (run from repo root)
Output: src/generated/layer{N}_etched.v (gitignored exhaust) — 30 files.
Requires: weights/bake/scales_cal.json (calibrate.py).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "src", "generated")
CAL = os.path.join(HERE, "scales_cal.json")

TMPL = """// GENERATED by weights/bake/emit_layers.py — do not hand-edit.
// Layer {n} etched wrapper: per-tensor weights + calibrated (MUL,SH)
// scale points (scales_cal.json). The netlist differs from every other
// layer through parameters alone.
module layer{n}_etched #(
  parameter S = 64,
  parameter H = 576,
  parameter KV = 192,
  parameter FF = 1536,
  parameter C = 256
)(
  input  wire             clk,
  input  wire             rst_n,
  input  wire [S*H*8-1:0] x_in,
  input  wire             x_valid,
  output wire             x_ready,
  output wire [S*H*8-1:0] x_out,
  output wire             y_valid
);
  layer_etched #(
    .S(S), .H(H), .KV(KV), .FF(FF), .C(C), .LAYER({n}),
    .WQ_FILE("weights/bake/layer{n}_q_proj_pt.hex"),
    .WK_FILE("weights/bake/layer{n}_k_proj_pt.hex"),
    .WV_FILE("weights/bake/layer{n}_v_proj_pt.hex"),
    .WQ_WIDE_FILE("weights/bake/layer{n}_q_proj_w32.hex"),
    .WK_WIDE_FILE("weights/bake/layer{n}_k_proj_w32.hex"),
    .WV_WIDE_FILE("weights/bake/layer{n}_v_proj_w32.hex"),
    .WO_FILE("weights/bake/layer{n}_o_proj_pt.hex"),
    .WG_FILE("weights/bake/layer{n}_gate_proj_pt.hex"),
    .WU_FILE("weights/bake/layer{n}_up_proj_pt.hex"),
    .WD_FILE("weights/bake/layer{n}_down_proj_pt.hex"),
    .WO_WIDE_FILE("weights/bake/layer{n}_o_proj_w32.hex"),
    .GN1_FILE("weights/bake/layer{n}_input_layernorm_q88.hex"),
    .GN2_FILE("weights/bake/layer{n}_post_attention_layernorm_q88.hex"),
    .SC_QKVM(16'd{qkvm}), .SC_QKVSH(5'd{qkvsh}),
    .SC_OM(16'd{om}), .SC_OSH(5'd{osh}),
    .G_MUL(16'd{gm}), .G_SH(5'd{gsh}),
    .U_MUL(16'd{um}), .U_SH(5'd{ush}),
    .P_MUL(16'd{pm}), .P_SH(5'd{psh}),
    .RQ_MUL(16'd{rqm}), .RQ_SH(5'd{rqsh}),
    .RS_MUL(16'd{rsm}), .RS_SH(5'd{rssh}),
    .YQ_SHIFT(5'd{yqsh})
  ) u_core (
    .clk(clk), .rst_n(rst_n),
    .x_in(x_in), .x_valid(x_valid), .x_ready(x_ready),
    .x_out(x_out), .y_valid(y_valid)
  );
endmodule
"""


def main():
    cal = json.load(open(CAL))
    assert len(cal["layers"]) == 30, "want 30 calibrated layers"
    os.makedirs(OUT, exist_ok=True)
    for n, L in enumerate(cal["layers"]):
        with open(os.path.join(OUT, "layer%d_etched.v" % n), "w") as f:
            f.write(TMPL.format(
                n=n, qkvm=L["SC_QKVM"], qkvsh=L["SC_QKVSH"],
                om=L["SC_OM"], osh=L["SC_OSH"],
                gm=L["G_MUL"], gsh=L["G_SH"],
                um=L["U_MUL"], ush=L["U_SH"],
                pm=L["P_MUL"], psh=L["P_SH"],
                rqm=L["RQ_MUL"], rqsh=L["RQ_SH"],
                rsm=L["RS_MUL"], rssh=L["RS_SH"],
                yqsh=L["YQ_SHIFT"]))
    print("emitted 30 calibrated wrappers -> %s" % OUT)


if __name__ == "__main__":
    main()
