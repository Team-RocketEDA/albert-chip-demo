#!/usr/bin/env python3
"""Emit per-layer etched wrappers (metaprogramming step).

One source (layer_etched.v) becomes 30 distinct netlists: each
src/generated/layerN_etched.v fixes LAYER=N plus that layer's seven
weight-file bindings, so Yosys elaborates 30 unique constant-folded
variants and each layerN_etched LibreLane config has a real top.

Only WQ/WK/WV bind today (inproj_tile takes W-file params); WO/WG/WU/WD
pass through layer_etched for the day outproj/ffn grow matching params.
All 30 default to layer-0 goldens until weights/bake/bake.py emits the
per-layer tables (same basenames, layerN_ prefix).

Usage: python3 weights/bake/emit_layers.py   (run from repo root)
Output: src/generated/layer{N}_etched.v (gitignored exhaust) — 30 files.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "src", "generated")

TMPL = """// GENERATED by weights/bake/emit_layers.py — do not hand-edit.
// Layer {n} etched wrapper: fixes this layer's weights so the netlist
// differs from every other layer through parameters alone.
module layer{n}_etched #(
  parameter S = 64,
  parameter H = 576,
  parameter KV = 192,
  parameter FF = 1536,
  parameter C = 256
)(
  input  wire             clk,
  input  wire             rst_n,
  input  wire [S*H*8-1:0] x_in,
  input  wire             x_valid,
  output wire             x_ready,
  output wire [S*H*8-1:0] x_out,
  output wire             y_valid
);
  layer_etched #(
    .S(S), .H(H), .KV(KV), .FF(FF), .C(C), .LAYER({n}),
    .WQ_FILE("weights/bake/layer{n}_q_proj.hex"),
    .WK_FILE("weights/bake/layer{n}_k_proj.hex"),
    .WV_FILE("weights/bake/layer{n}_v_proj.hex"),
    .WO_FILE("weights/bake/layer{n}_o_proj.hex"),
    .WG_FILE("weights/bake/layer{n}_gate_proj.hex"),
    .WU_FILE("weights/bake/layer{n}_up_proj.hex"),
    .WD_FILE("weights/bake/layer{n}_down_proj.hex")
  ) u_core (
    .clk(clk), .rst_n(rst_n),
    .x_in(x_in), .x_valid(x_valid), .x_ready(x_ready),
    .x_out(x_out), .y_valid(y_valid)
  );
endmodule
"""


def main():
    os.makedirs(OUT, exist_ok=True)
    for n in range(30):
        with open(os.path.join(OUT, "layer%d_etched.v" % n), "w") as f:
            f.write(TMPL.format(n=n))
    print("emitted 30 wrappers -> %s" % OUT)


if __name__ == "__main__":
    main()
