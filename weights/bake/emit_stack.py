#!/usr/bin/env python3
"""Emit the weight-bound 30-layer stack (metaprogramming step).

decoder_etched_stack.v binds layer-0 tables into all 30 macros (noted in
its header); this emits src/generated/decoder_stack_bound.v with 30
EXPLICIT layer_etched instances, each fixed to its own baked tables
(byte + w32 + Q8.8 norms), so token-level sims (codec bench) and any
future full-stack run use TRUE per-layer weights. Same port signature
and S/H/KV/FF params as decoder_etched_stack.

Usage: python3 weights/bake/emit_stack.py
Output: src/generated/decoder_stack_bound.v (gitignored exhaust).
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "src", "generated")
CAL = os.path.join(HERE, "scales_cal.json")

HEAD = """// GENERATED by weights/bake/emit_stack.py — do not hand-edit.
// Weight-bound 30-layer etched stack: macro k owns layer-k tables.
module decoder_stack_bound #(
  parameter S = 64,
  parameter H = 576,
  parameter KV = 192,
  parameter FF = 1536
)(
  input  wire             clk,
  input  wire             rst_n,
  input  wire [S*H*8-1:0] x_in,
  input  wire             x_valid,
  output wire             x_ready,
  output wire [S*H*8-1:0] x_out,
  output wire             y_valid
);
  wire [S*H*8-1:0] d [0:28];
  wire [29:0]      vld;
"""

INST = """  layer_etched #(
    .S(S), .H(H), .KV(KV), .FF(FF), .LAYER({n}),
    .WQ_FILE("weights/bake/layer{n}_q_proj_pt.hex"),
    .WK_FILE("weights/bake/layer{n}_k_proj_pt.hex"),
    .WV_FILE("weights/bake/layer{n}_v_proj_pt.hex"),
    .WO_FILE("weights/bake/layer{n}_o_proj_pt.hex"),
    .WG_FILE("weights/bake/layer{n}_gate_proj_pt.hex"),
    .WU_FILE("weights/bake/layer{n}_up_proj_pt.hex"),
    .WD_FILE("weights/bake/layer{n}_down_proj_pt.hex"),
    .WQ_WIDE_FILE("weights/bake/layer{n}_q_proj_w32.hex"),
    .WK_WIDE_FILE("weights/bake/layer{n}_k_proj_w32.hex"),
    .WV_WIDE_FILE("weights/bake/layer{n}_v_proj_w32.hex"),
    .WO_WIDE_FILE("weights/bake/layer{n}_o_proj_w32.hex"),
    .GN1_FILE("weights/bake/layer{n}_input_layernorm_q88.hex"),
    .GN2_FILE("weights/bake/layer{n}_post_attention_layernorm_q88.hex"),
    .SC_QKVM(16'd{qkvm}), .SC_QKVSH(5'd{qkvsh}),
    .SC_OM(16'd{om}), .SC_OSH(5'd{osh}),
    .G_MUL(16'd{gm}), .G_SH(5'd{gsh}),
    .U_MUL(16'd{um}), .U_SH(5'd{ush}),
    .P_MUL(16'd{pm}), .P_SH(5'd{psh}),
    .RQ_MUL(16'd{rqm}), .RQ_SH(5'd{rqsh}),
    .RS_MUL(16'd{rsm}), .RS_SH(5'd{rssh}),
    .YQ_SHIFT(5'd{yqsh})
  ) u_l{n} (
    .clk(clk), .rst_n(rst_n),
    .x_in({xin}), .x_valid({xv}), .x_ready({xr}),
    .x_out({xo}), .y_valid({yv})
  );
"""

TAIL = """endmodule
"""


def main():
    """CLI entry point (see module docstring for usage)."""
    os.makedirs(OUT, exist_ok=True)
    cal = json.load(open(CAL))["layers"]
    assert len(cal) == 30, "want 30 calibrated layers"
    lines = [HEAD]
    for n in range(30):
        if n == 0:
            xin, xv, xr, xo, yv = "x_in", "x_valid", "x_ready", "d[0]", "vld[0]"
        elif n == 29:
            xin, xv, xr, xo, yv = ("d[28]", "vld[28]", "",
                                   "x_out", "y_valid")
        else:
            xin, xv, xr, xo, yv = ("d[%d]" % (n - 1), "vld[%d]" % (n - 1),
                                   "", "d[%d]" % n, "vld[%d]" % n)
        L = cal[n]
        lines.append(INST.format(
            n=n, xin=xin, xv=xv, xr=xr if xr else "", xo=xo, yv=yv,
            qkvm=L["SC_QKVM"], qkvsh=L["SC_QKVSH"],
            om=L["SC_OM"], osh=L["SC_OSH"],
            gm=L["G_MUL"], gsh=L["G_SH"],
            um=L["U_MUL"], ush=L["U_SH"],
            pm=L["P_MUL"], psh=L["P_SH"],
            rqm=L["RQ_MUL"], rqsh=L["RQ_SH"],
            rsm=L["RS_MUL"], rssh=L["RS_SH"],
            yqsh=L["YQ_SHIFT"]))
    lines.append(TAIL)
    path = os.path.join(OUT, "decoder_stack_bound.v")
    with open(path, "w") as f:
        f.writelines(lines)
    print("emitted bound stack -> %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
