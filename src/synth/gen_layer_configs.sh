#!/usr/bin/env bash
# gen_layer_configs.sh — GENERATOR for per-block LibreLane Classic configs.
#
# Owns ONLY new dirs under src/synth/: layer{0..29}_etched/, embed_top/,
# ffn_tile/. Template = src/synth/attention_core/* (LibreLane Classic,
# sky130A, sky130_fd_sc_hd) with DESIGN/DIE/VERILOG substituted.
#
# One-layer-per-run only: each layerN_etched block is sized for ONE layer
# macro (DIE 2000). Never the full 30-layer model in one run (OOM kills).
#
# Usage: bash src/synth/gen_layer_configs.sh   (run from repo root)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
cd "$REPO"

# PDK root: $PDK wins, else well-known locations. Override per-machine with
# PDK=/path/to/sky130A — never edit this file for paths. Generated configs
# embed the resolved absolute LIB paths (local exhaust); re-run this script
# on a new machine to re-resolve.
if [ -z "${PDK:-}" ]; then
  for c in "$HOME/.volare/sky130A" "$HOME/.local/share/pdk/sky130A" "${PDK_ROOT:-}/sky130A" /usr/share/pdk/sky130A; do
    if [ -d "$c" ]; then PDK="$c"; break; fi
  done
fi
: "${PDK:?PDK root not found — set PDK=/path/to/sky130A}"
LIBBASE="$PDK/libs.ref/sky130_fd_sc_hd/lib"
LIB_TT="$LIBBASE/sky130_fd_sc_hd__tt_100C_1v80.lib"
LIB_SS="$LIBBASE/sky130_fd_sc_hd__ss_100C_1v60.lib"
LIB_FF="$LIBBASE/sky130_fd_sc_hd__ff_n40C_1v95.lib"

# Transitive VERILOG_FILES (repo-relative) per block.
LAYER_FILES="src/components/attention_core.v src/components/div_unit.v src/components/exp_lut.v src/components/fifo_sync.v src/components/ffn_tile.v src/components/inproj_tile.v src/components/layer_etched.v src/components/mac_array.v src/components/outproj_tile.v src/components/regfile_dp.v src/components/requant.v src/components/rmsnorm_d.v src/components/rmsnorm_stage.v src/components/seq_fsm.v src/components/silu_lut.v src/components/softmax_d.v src/components/sram_1r1w.v"
FFN_FILES="src/components/ffn_tile.v src/components/fifo_sync.v src/components/mac_array.v src/components/regfile_dp.v src/components/requant.v src/components/seq_fsm.v src/components/silu_lut.v src/components/sram_1r1w.v"
EMBED_FILES="src/components/embed_top.v src/components/embed_lut.v src/components/fifo_sync.v src/components/seq_fsm.v src/components/sram_1r1w.v"

emit_block() {
  # args: $1=dir name (e.g. layer0_etched)  $2=DESIGN_NAME  $3=DIE  $4=space-sep VERILOG_FILES
  local dir="$1" design="$2" die="$3" files="$4"
  local core=$((die - 30))
  local d="src/synth/$dir"
  mkdir -p "$d/nl" "$d/pnr"

  # --- config.json (LibreLane Classic, sky130A, sky130_fd_sc_hd) ---
  {
    echo "{"
    echo "  \"DESIGN_NAME\": \"$design\","
    printf "  \"VERILOG_FILES\": ["
    local first=1 f
    for f in $files; do
      if [ $first -eq 1 ]; then first=0; else printf ", "; fi
      printf "\"%s\"" "$f"
    done
    printf "],\n"
    cat <<JSON
  "CLOCK_PORT": "clk",
  "CLOCK_PERIOD": 25,
  "PDK": "sky130A",
  "STD_CELL_LIBRARY": "sky130_fd_sc_hd",
  "LIB": {
    "*tt*": ["$LIB_TT"],
    "*ss*": ["$LIB_SS"],
    "*ff*": ["$LIB_FF"]
  },
  "STA_CORNERS": ["nom_tt_025C_1v80", "nom_ss_100C_1v60", "nom_ff_n40C_1v95", "min_tt_025C_1v80", "min_ss_100C_1v60", "min_ff_n40C_1v95", "max_tt_025C_1v80", "max_ss_100C_1v60", "max_ff_n40C_1v95"],
  "DEFAULT_CORNER": "nom_tt_025C_1v80",
  "SYNTH_STRATEGY": "AREA 0",
  "FP_SIZING": "absolute",
  "DIE_AREA": [0, 0, $die, $die],
  "RUN_TAG": "demo"
}
JSON
  } > "$d/config.json"

  # --- synth.ys.in ---
  {
    echo "# synth.ys — yosys synthesis of $design to sky130_fd_sc_hd (tt)."
    echo "# GENERATED by gen_layer_configs.sh — do not hand-edit. Run via run.sh"
    echo "# (yosys CWD = repo root so baked \$readmemh paths resolve)."
    for f in $files; do
      echo "read_verilog @REPO@/$f"
    done
    cat <<YS
hierarchy -check -top $design
proc; opt; fsm; opt; memory; opt
booth
techmap; opt
dfflibmap -liberty @LIB@
opt
abc -liberty @LIB@
opt; clean
stat
tee -o @HERE@/nl/report.txt stat
write_verilog -noattr -noexpr -nohex -nodec @HERE@/nl/$design.nl.v
YS
  } > "$d/synth.ys.in"

  # --- run.sh ---
  cat > "$d/run.sh" <<SH
#!/usr/bin/env bash
# $design sky130 P&R (librelane-devshell toolchain, repo-driven flow).
# GENERATED by gen_layer_configs.sh — do not hand-edit; edit the generator.
# Real GDS for $design with baked weight tables etched (\$readmemh ROMs
# elaborated by yosys from REPO root so the bake paths resolve).
#   bash run.sh   # synth -> P&R -> GDS -> PNG screenshot
# ONE BLOCK PER RUN: this dir sizes ONE macro only (never the full model).
set -euo pipefail
HERE="\$(cd "\$(dirname "\$0")" && pwd)"
REPO="\$(cd "\$HERE/../../.." && pwd)"
# PDK: \$PDK wins, else well-known locations (same rule as build.sh prereqs).
if [ -z "\${PDK:-}" ]; then
  for c in "\$HOME/.volare/sky130A" "\$HOME/.local/share/pdk/sky130A" "\${PDK_ROOT:-}/sky130A" /usr/share/pdk/sky130A; do
    if [ -d "\$c" ]; then PDK="\$c"; break; fi
  done
fi
: "\${PDK:?set PDK=/path/to/sky130A}"
LIB="\$PDK/libs.ref/sky130_fd_sc_hd/lib/sky130_fd_sc_hd__tt_100C_1v80.lib"
# Tools: \$TOOL_YOSYS/\$TOOL_OPENROAD/\$TOOL_MAGIC/\$TOOL_KLAYOUT win when set.
# Magic default is the source build on PATH (/usr/local/bin/magic), NOT nix.
# Yosys/OpenROAD/KLayout default to the librelane-devshell nix layout.
NIX=/tmp/librelane-shell/squashfs-root/nix/store
YOSYS=\${TOOL_YOSYS:-\$(echo \$NIX/*-yosys-0.62/bin/yosys)}
OPENROAD=\${TOOL_OPENROAD:-\$(echo \$NIX/*-openroad-2026-02-17/bin/openroad)}
MAGIC=\${TOOL_MAGIC:-\$(command -v magic)}
KLAYOUT=\${TOOL_KLAYOUT:-\$(echo \$NIX/*-klayout-0.30.7/bin/klayout)}

export REPO PDK LIB
mkdir -p "\$HERE/nl" "\$HERE/pnr"
echo "[1/4] synth (yosys)";       sed -e "s|@REPO@|\$REPO|g" -e "s|@LIB@|\$LIB|g" -e "s|@HERE@|\$HERE|g" "\$HERE/synth.ys.in" > "\$HERE/synth.gen.ys" && (cd "\$REPO" && "\$YOSYS" -q -s "\$HERE/synth.gen.ys") 2>&1 | tail -5
echo "[2/4] place";                "\$OPENROAD" -no_splash -exit "\$HERE/pnr.tcl" 2>&1 | tee -a "\$HERE/run.log" | tail -3
echo "[2b/4] route";               "\$OPENROAD" -no_splash -exit "\$HERE/pnr_route.tcl" 2>&1 | tee -a "\$HERE/run.log" | tail -5
echo "[3/4] GDS merge (magic)";   (cd "\$HERE" && "\$MAGIC" -dnull -noconsole -rcfile "\$PDK/libs.tech/magic/sky130A.magicrc" merge.tcl 2>&1 | tail -3)
echo "[4/4] screenshot (klayout)"; "\$KLAYOUT" -b -r "\$HERE/shot.py" 2>&1 | tail -3
echo "done: \$HERE/$design.gds \$HERE/${design}_top.png"
SH
  chmod +x "$d/run.sh"

  # --- pnr.tcl ---
  cat > "$d/pnr.tcl" <<TCL
# pnr.tcl — OpenROAD floorplan/place for $design (demo scope).
# GENERATED by gen_layer_configs.sh — do not hand-edit.
# Single ideal clock, no CTS, no power grid (tapcells + abutted rows).
# Run via run.sh. Env: PDK, LIB.
set PDK \$::env(PDK)
set LIB \$::env(LIB)
set HERE [file dirname [info script]]

read_liberty \$LIB
read_lef \$PDK/libs.ref/sky130_fd_sc_hd/techlef/sky130_fd_sc_hd__nom.tlef
read_lef \$PDK/libs.ref/sky130_fd_sc_hd/lef/sky130_fd_sc_hd.lef
read_verilog \$HERE/nl/$design.nl.v
link_design $design

create_clock -name clk -period 25 [get_ports clk]
set_clock_uncertainty 0.5 [get_clocks clk]

initialize_floorplan -die_area "0 0 $die $die" -core_area "15 15 $core $core" -site unithd
make_tracks
tapcell \\
  -tapcell_master sky130_fd_sc_hd__tap_1 \\
  -endcap_master sky130_fd_sc_hd__decap_3 \\
  -distance 14

global_placement -skip_io
repair_design
place_pins -hor_layers met3 -ver_layers met2
detailed_placement
detailed_placement -disallow_one_site_gaps

# DEF round-trip: drops the pinless tapcell power phantom
# so TritonRoute only sees real SIGNAL nets.
write_def \$HERE/pnr/$design.placed.def
puts "PLACE DONE"
TCL

  # --- pnr_route.tcl ---
  cat > "$d/pnr_route.tcl" <<TCL
# pnr_route.tcl — OpenROAD global+detail route from placed DEF (demo scope).
# GENERATED by gen_layer_configs.sh — do not hand-edit. Part of run.sh.
set PDK \$::env(PDK)
set HERE [file dirname [info script]]

read_lef \$PDK/libs.ref/sky130_fd_sc_hd/techlef/sky130_fd_sc_hd__nom.tlef
read_lef \$PDK/libs.ref/sky130_fd_sc_hd/lef/sky130_fd_sc_hd.lef
read_def \$HERE/pnr/$design.placed.def

# Tapcell power nets are real and connected but have no grid; mark them
# special so the routers skip them (librelane pdn_cfg.tcl same pattern).
set block [ord::get_db_block]
foreach {nm ty} {one_ POWER zero_ GROUND} {
  set n [\$block findNet \$nm]
  if {\$n != "NULL"} { \$n setSpecial; \$n setSigType \$ty }
}

create_clock -name clk -period 25 [get_ports clk]
set_clock_uncertainty 0.5 [get_clocks clk]

global_route -verbose
detailed_route -output_maze \$HERE/pnr/route.maze.log -output_drc \$HERE/pnr/route.drc
report_checks -path_delay min_max -format full_clock_expanded -fields {input_pins nets} -digits 4 > \$HERE/pnr/timing.rpt
report_check_types -max_violation_count 10 > \$HERE/pnr/drc.rpt
write_def \$HERE/pnr/$design.def
write_verilog \$HERE/pnr/$design.pnr.v
puts "PNR DONE"
TCL

  # --- merge.tcl ---
  cat > "$d/merge.tcl" <<TCL
-- merge.tcl — magic batch LEF/DEF -> GDS (run via run.sh in this dir).
-- GENERATED by gen_layer_configs.sh — do not hand-edit.
lef read \$::env(PDK)/libs.ref/sky130_fd_sc_hd/techlef/sky130_fd_sc_hd__nom.tlef
lef read \$::env(PDK)/libs.ref/sky130_fd_sc_hd/lef/sky130_fd_sc_hd.lef
def read pnr/$design.def
load $design
gds write $design.gds
quit -noprompt
TCL

  # --- shot.py ---
  cat > "$d/shot.py" <<PY
# shot.py — klayout batch GDS screenshot (run via run.sh in this dir).
# GENERATED by gen_layer_configs.sh — do not hand-edit.
import os
import pya

here = os.path.dirname(os.path.abspath(__file__))
tech_file = os.path.join(os.environ["PDK"], "libs.tech", "klayout", "tech", "sky130A.lyt")

view = pya.Application.instance().main_window().create_view()
tech = pya.Technology.technology_from_xml(tech_file)
view.set_config("background-color", "#ffffff")
layout = view.load_layout(os.path.join(here, "$design.gds"), tech, 0)
view.max_hier()
view.zoom_fit()
view.save_image(os.path.join(here, "${design}_top.png"), 1200, 900)
print("SHOT DONE")
PY
  echo "emitted $d ($design, die $die)"
}

# 30 unrolled layer macros: ONE layer per run (DIE 2000 — one macro only).
# Each gets its metaprogrammed wrapper (emit_layers.py exhaust) as the
# hierarchy top, so DESIGN_NAME resolves to a distinct netlist per layer.
for i in $(seq 0 29); do
  emit_block "layer${i}_etched" "layer${i}_etched" 2000 \
    "$LAYER_FILES src/generated/layer${i}_etched.v"
done

# Companion small blocks by the same template.
emit_block "ffn_tile" "ffn_tile" 1200 "$FFN_FILES"
emit_block "embed_top" "embed_top" 800 "$EMBED_FILES"

echo "OK: 30 layers + ffn_tile + embed_top"
