// exp_lut — softmax exp table (+ rsqrt seed shape). Contract:
// blocks/03-attention-core.md sub_exp + blocks/00-primitive-library.md §E.
//
// y = exp(d), d = score - row_max (<= 0 after max-sub), Q4.12 in/out
// (PARAMS §2; output range (0, 1] fits Q4.12).
// 256x16b ROM + linear interp via inferred operators only (1 mult + 1 adder
// per 03; no single-operator modules):
//   t    = d + 32768, signed (0..32768 for d in [-8, 0]; floor is exact)
//   idx  = t[15:7]  (0..256, table step 128 LSB = 1/32)
