//   y = rom[idx] + round((rom[idx+1]-rom[idx]) * frac / 128), half-up
// rom spans [-8.0, -1/32]; the one-past-the-end point is TOP = exp(0) = 1.0
// (0x1000), shared with the x == 0 tap. Inputs > 0 cannot occur after
// max-sub; they are a documented clamp to 0x1000 (also x == 0).
// Table contents were generated by an independent pure-python oracle
// (same method as src/tb/exp_lut/gen_golden.py); full-domain error vs
// round-to-nearest float exp is <= 1 LSB, acceptance is 2 LSB
// (see src/tb/exp_lut/tb_exp_lut.v).
// Purely combinational; no clock. W is kept for interface uniformity —
// the table is inherently 16-bit (Q4.12).
